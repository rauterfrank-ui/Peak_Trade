def _validate_loaded_join_payload_v1(
    payload: Mapping[str, Any],
) -> CanonicalVolatilityMaxAgeResearchEvidenceJoinV1:
    if not isinstance(payload, Mapping):
        raise MaxAgeResearchDesignContractError("ledger_record_must_be_object")
    if payload.get("enforcement_applied") is True:
        raise MaxAgeResearchDesignContractError("ledger_contains_enforcement")
    if payload.get("numeric_threshold_selected") is True:
        raise MaxAgeResearchDesignContractError("ledger_contains_numeric_threshold_selected")
    threshold_status = _require_nonempty_identity(
        payload.get("threshold_status"),
        field_name="threshold_status",
    )
    if threshold_status != THRESHOLD_STATUS_UNRESOLVED:
        raise MaxAgeResearchDesignContractError("ledger_requires_unresolved_threshold")

    join = _join_from_mapping_v1(payload)
    stored_digest = _require_nonempty_identity(payload.get("join_digest"), field_name="join_digest")
    if stored_digest != join.join_digest:
        raise MaxAgeResearchDesignContractError("ledger_join_digest_mismatch")
    return join


def _apply_duplicate_policy_v1(
    *,
    existing: Sequence[Mapping[str, Any]],
    candidate: CanonicalVolatilityMaxAgeResearchEvidenceJoinV1,
) -> CanonicalVolatilityMaxAgeResearchEvidenceJoinV1 | None:
    """Return None to append; return candidate for identical idempotent no-op."""
    business = candidate.business_identity_v1()
    for raw in existing:
        existing_join = _validate_loaded_join_payload_v1(raw)
        if existing_join.business_identity_v1() != business:
            continue
        if existing_join.join_digest == candidate.join_digest:
            return candidate
        raise MaxAgeResearchDesignContractError("ledger_duplicate_identity_digest_conflict")
    return None


def append_max_age_research_evidence_ledger_record_v1(
    *,
    ledger_path: Path,
    record: Union[CanonicalVolatilityMaxAgeResearchEvidenceJoinV1, Mapping[str, Any]],
) -> CanonicalVolatilityMaxAgeResearchEvidenceJoinV1:
    """Append one join record to a durable JSONL ledger (multi-session corpus)."""
    if isinstance(record, CanonicalVolatilityMaxAgeResearchEvidenceJoinV1):
        join = record
    else:
        join = _join_from_mapping_v1(record)

    if join.enforcement_applied:
        raise MaxAgeResearchDesignContractError("ledger_forbids_enforcement_applied")
    if join.threshold_status != THRESHOLD_STATUS_UNRESOLVED:
        raise MaxAgeResearchDesignContractError("ledger_requires_unresolved_threshold")
    recomputed = _join_digest_v1(join.to_dict())
    if recomputed != join.join_digest:
        raise MaxAgeResearchDesignContractError("ledger_join_digest_mismatch")

    ledger_path = Path(ledger_path)
    existing = load_max_age_research_evidence_ledger_v1(ledger_path)
    duplicate = _apply_duplicate_policy_v1(existing=existing, candidate=join)
    if duplicate is not None:
        return duplicate

    ledger_path.parent.mkdir(parents=True, exist_ok=True)
    line = json.dumps(join.to_dict(), sort_keys=True, separators=(",", ":"), default=str)
    with ledger_path.open("a", encoding="utf-8") as handle:
        handle.write(line + "\n")
    return join


def load_max_age_research_evidence_ledger_v1(
    ledger_path: Path,
) -> list[dict[str, Any]]:
    path = Path(ledger_path)
    if not path.exists():
        return []
    records: list[dict[str, Any]] = []
    seen_business: dict[tuple[str, str, str, str], str] = {}
    try:
        raw_text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise MaxAgeResearchDesignContractError(f"ledger_read_failed:{exc}") from exc

    for line_no, raw in enumerate(raw_text.splitlines(), start=1):
        line = raw.strip()
        if not line:
            continue
        try:
            payload = json.loads(line)
        except json.JSONDecodeError as exc:
            raise MaxAgeResearchDesignContractError(
                f"ledger_corrupt_json:line={line_no}:{exc.msg}"
            ) from exc
        if not isinstance(payload, dict):
            raise MaxAgeResearchDesignContractError(f"ledger_record_must_be_object:line={line_no}")
        join = _validate_loaded_join_payload_v1(payload)
        business = join.business_identity_v1()
        prior_digest = seen_business.get(business)
        if prior_digest is not None:
            if prior_digest != join.join_digest:
                raise MaxAgeResearchDesignContractError(
                    f"ledger_duplicate_identity_digest_conflict:line={line_no}"
                )
            # Identical duplicate in durable ledger is corruption for load order;
            # fail-closed rather than silently collapsing.
            raise MaxAgeResearchDesignContractError(
                f"ledger_duplicate_identity_repeated:line={line_no}"
            )
        seen_business[business] = join.join_digest
        records.append(join.to_dict())
    return records


def summarize_max_age_research_evidence_accumulation_v1(
    records: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    """Multi-session / multi-regime coverage summary (no threshold selection)."""
    sessions = sorted({str(r.get("session_id") or "") for r in records if r.get("session_id")})
    regimes = sorted({str(r.get("regime_id") or "") for r in records if r.get("regime_id")})
    instruments = sorted(
        {str(r.get("instrument_id") or "") for r in records if r.get("instrument_id")}
    )
    reuse_labels = sorted(
        {str(r.get("reuse_status") or "") for r in records if r.get("reuse_status")}
    )
    restart_labels = sorted(
        {str(r.get("restart_status") or "") for r in records if r.get("restart_status")}
    )
    ages = [
        float(r["computed_age_seconds"])
        for r in records
        if r.get("computed_age_seconds") is not None
    ]
    return {
        "accumulation_ledger_version": ACCUMULATION_LEDGER_VERSION,
        "record_count": len(records),
        "session_count": len(sessions),
        "regime_count": len(regimes),
        "instrument_count": len(instruments),
        "sessions": sessions,
        "regimes": regimes,
        "instruments": instruments,
        "reuse_status_labels": reuse_labels,
        "restart_status_labels": restart_labels,
        "computed_age_observations": len(ages),
        "threshold_status": THRESHOLD_STATUS,
        "numeric_max_age_decided": NUMERIC_MAX_AGE_DECIDED,
        "enforcement_enabled": ENFORCEMENT_ENABLED,
        "enforcement_applied": ENFORCEMENT_APPLIED,
        "parameter_research_executed": PARAMETER_RESEARCH_EXECUTED,
        "multi_session_coverage": len(sessions) >= 2,
        "multi_regime_coverage": len(regimes) >= 2,
    }


def accumulate_max_age_research_evidence_record_from_cycle_v1(
    cycle: Mapping[str, Any],
    *,
    ledger_path: Path | None = None,
    in_memory_ledger: list[dict[str, Any]] | None = None,
) -> CanonicalVolatilityMaxAgeResearchEvidenceJoinV1:
    """Join a cycle, optionally append to durable + in-memory research ledgers."""
    join = build_max_age_research_evidence_join_from_cycle_v1(cycle)
    payload = join.to_dict()

    if in_memory_ledger is not None:
        duplicate = _apply_duplicate_policy_v1(existing=in_memory_ledger, candidate=join)
        if duplicate is None:
            in_memory_ledger.append(dict(payload))

    if ledger_path is not None:
        append_max_age_research_evidence_ledger_record_v1(
            ledger_path=ledger_path,
            record=join,
        )
    return join


