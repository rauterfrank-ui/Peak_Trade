def evaluate_counterfactual_max_age_threshold_diagnostic_v1(
    *,
    computed_age_seconds: Optional[float],
    candidate_max_age_seconds_argument: float,
) -> CounterfactualMaxAgeThresholdDiagnosticV1:
    """Deterministic counterfactual age label; never enforces Alpha decisions."""
    if (
        not isinstance(candidate_max_age_seconds_argument, (int, float))
        or isinstance(candidate_max_age_seconds_argument, bool)
        or candidate_max_age_seconds_argument < 0.0
    ):
        return CounterfactualMaxAgeThresholdDiagnosticV1(
            computed_age_seconds=computed_age_seconds,
            candidate_max_age_seconds_argument=float("nan"),
            counterfactual_label=CounterfactualAgeLabelV1.THRESHOLD_ARGUMENT_INVALID.value,
            enforcement_applied=False,
            alpha_decision_mutated=False,
            threshold_status_productive=THRESHOLD_STATUS,
            evaluation_mode="DIAGNOSTIC_COUNTERFACTUAL_NO_ENFORCEMENT",
        )

    candidate = float(candidate_max_age_seconds_argument)
    if computed_age_seconds is None:
        label = CounterfactualAgeLabelV1.AGE_UNAVAILABLE
    elif float(computed_age_seconds) <= candidate:
        label = CounterfactualAgeLabelV1.WOULD_BE_FRESH_IF_THRESHOLD
    else:
        label = CounterfactualAgeLabelV1.WOULD_BE_STALE_IF_THRESHOLD

    return CounterfactualMaxAgeThresholdDiagnosticV1(
        computed_age_seconds=None if computed_age_seconds is None else float(computed_age_seconds),
        candidate_max_age_seconds_argument=candidate,
        counterfactual_label=label.value,
        enforcement_applied=False,
        alpha_decision_mutated=False,
        threshold_status_productive=THRESHOLD_STATUS,
        evaluation_mode="DIAGNOSTIC_COUNTERFACTUAL_NO_ENFORCEMENT",
    )


