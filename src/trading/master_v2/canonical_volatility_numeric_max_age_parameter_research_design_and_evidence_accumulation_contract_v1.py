def validate_max_age_research_design_contract_v1(
    contract: CanonicalVolatilityMaxAgeResearchDesignContractV1,
) -> CanonicalVolatilityMaxAgeResearchDesignContractV1:
    if contract.preregistration_contract_version != PREREGISTRATION_CONTRACT_VERSION:
        raise MaxAgeResearchDesignContractError("preregistration_contract_version_mismatch")
    if contract.threshold_status != THRESHOLD_STATUS_UNRESOLVED:
        raise MaxAgeResearchDesignContractError("threshold_must_remain_unresolved")
    if contract.numeric_max_age_seconds is not None:
        raise MaxAgeResearchDesignContractError("numeric_max_age_seconds_must_be_null")
    if (
        contract.enforcement_enabled
        or contract.enforcement_applied
        or contract.alpha_enforcement_allowed
    ):
        raise MaxAgeResearchDesignContractError("enforcement_forbidden")
    if contract.parameter_research_executed:
        raise MaxAgeResearchDesignContractError("parameter_research_execution_forbidden")
    if contract.age_reference_clock != AGE_REFERENCE_CLOCK:
        raise MaxAgeResearchDesignContractError("age_reference_clock_mismatch")

    _require_nonempty_text(contract.research_question, field_name="research_question")
    _require_nonempty_text(
        contract.candidate_threshold_source, field_name="candidate_threshold_source"
    )
    _require_nonempty_text(contract.dataset_scope, field_name="dataset_scope")
    _require_nonempty_text(contract.session_scope, field_name="session_scope")
    _require_nonempty_text(contract.instrument_scope, field_name="instrument_scope")
    _require_nonempty_text(contract.cost_assumptions, field_name="cost_assumptions")
    _require_nonempty_text(contract.purged_split_policy, field_name="purged_split_policy")
    _require_nonempty_text(contract.embargo_policy, field_name="embargo_policy")
    _require_nonempty_text(contract.walk_forward_design, field_name="walk_forward_design")
    _require_nonempty_text(contract.final_holdout_policy, field_name="final_holdout_policy")
    _require_nonempty_str_tuple(contract.candidate_dimensions, field_name="candidate_dimensions")
    _require_nonempty_str_tuple(contract.regime_dimensions, field_name="regime_dimensions")
    _require_nonempty_str_tuple(contract.metrics, field_name="metrics")
    _require_nonempty_str_tuple(contract.leakage_controls, field_name="leakage_controls")
    _require_nonempty_str_tuple(contract.stress_controls, field_name="stress_controls")
    _require_nonempty_str_tuple(contract.robustness_controls, field_name="robustness_controls")
    _require_nonempty_str_tuple(contract.rejection_criteria, field_name="rejection_criteria")
    _require_nonempty_str_tuple(contract.selection_criteria, field_name="selection_criteria")
    if not isinstance(contract.minimum_evidence_requirements, Mapping):
        raise MaxAgeResearchDesignContractError("minimum_evidence_requirements_required")
    if not contract.minimum_evidence_requirements:
        raise MaxAgeResearchDesignContractError("minimum_evidence_requirements_required")

    forbidden_selection_tokens = (
        "best sharpe",
        "maximum pnl",
        "maximum trade count",
        "single best configuration",
    )
    selection_blob = " ".join(contract.selection_criteria).lower()
    for token in forbidden_selection_tokens:
        if token in selection_blob:
            raise MaxAgeResearchDesignContractError("forbidden_point_selection_rule")
    required_selection = {
        MaxAgeSelectionCriterionV1.ROBUST_THRESHOLD_REGION_NOT_POINT.value,
        MaxAgeSelectionCriterionV1.MULTI_SESSION_AGREEMENT_REQUIRED.value,
        MaxAgeSelectionCriterionV1.MULTI_REGIME_AGREEMENT_REQUIRED.value,
        MaxAgeSelectionCriterionV1.FINAL_HOLDOUT_CONFIRMATION_REQUIRED.value,
        MaxAgeSelectionCriterionV1.NO_BEST_SHARPE_POINT_SELECTION.value,
        MaxAgeSelectionCriterionV1.NO_MAX_PNL_POINT_SELECTION.value,
        MaxAgeSelectionCriterionV1.NO_MAX_TRADE_COUNT_POINT_SELECTION.value,
    }
    if not required_selection.issubset(set(contract.selection_criteria)):
        raise MaxAgeResearchDesignContractError("selection_criteria_incomplete")

    expected_digest = _preregistration_digest_v1(contract.to_dict())
    if contract.preregistration_digest != expected_digest:
        raise MaxAgeResearchDesignContractError("preregistration_digest_mismatch")
    return contract


