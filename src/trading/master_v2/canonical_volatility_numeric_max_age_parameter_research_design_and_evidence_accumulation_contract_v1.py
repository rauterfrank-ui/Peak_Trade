def _canonical_json_bytes(payload: Mapping[str, Any]) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")


def _sha256_hex(payload: Mapping[str, Any]) -> str:
    return hashlib.sha256(_canonical_json_bytes(payload)).hexdigest()


def _require_nonempty_identity(value: Any, *, field_name: str) -> str:
    if value is None:
        raise MaxAgeResearchDesignContractError(f"{field_name}_required")
    text = str(value).strip()
    if not text:
        raise MaxAgeResearchDesignContractError(f"{field_name}_must_be_nonempty")
    return text


def _require_nonempty_text(value: Any, *, field_name: str) -> str:
    return _require_nonempty_identity(value, field_name=field_name)


def _require_nonempty_str_tuple(values: Sequence[Any], *, field_name: str) -> tuple[str, ...]:
    if not values:
        raise MaxAgeResearchDesignContractError(f"{field_name}_required")
    out: list[str] = []
    for item in values:
        out.append(_require_nonempty_text(item, field_name=field_name))
    return tuple(out)


def _as_optional_int(value: Any) -> Optional[int]:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _as_optional_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _as_optional_bool(value: Any) -> Optional[bool]:
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    return None


def _optional_identity(value: Any) -> Optional[str]:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _assert_identity_agreement(
    *,
    field_name: str,
    expected: str,
    observed: Any,
) -> None:
    observed_id = _optional_identity(observed)
    if observed_id is None:
        return
    if observed_id != expected:
        raise MaxAgeResearchDesignContractError(f"cross_{field_name}_join_conflict")


